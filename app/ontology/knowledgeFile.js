// ontology/knowledgeFile.js: validate, save and export the knowledge file (the ontology).
//
// The knowledge file is plain JSON read fresh on every request (knowledge.js), so a save here changes the
// next answer for every caller: the web app, the API and every MCP client.

import fs from "node:fs";
import path from "node:path";

const MAX_ENTRIES = 5000;
const MAX_TEXT = 2000;

const isText = (v) => typeof v === "string";

// Returns { ok: true, value } with only the four known sections, or { ok: false, error }.
export function validateKnowledge(input) {
  if (!input || typeof input !== "object" || Array.isArray(input)) return { ok: false, error: "The knowledge file must be a JSON object." };
  const out = { descriptions: {}, expressions: {}, examples: [], instructions: [] };
  for (const section of ["descriptions", "expressions"]) {
    const v = input[section] ?? {};
    if (typeof v !== "object" || Array.isArray(v)) return { ok: false, error: `"${section}" must be an object of name -> text.` };
    const entries = Object.entries(v);
    if (entries.length > MAX_ENTRIES) return { ok: false, error: `"${section}" has more than ${MAX_ENTRIES} entries.` };
    for (const [k, text] of entries) {
      if (!k.trim()) return { ok: false, error: `"${section}" has an empty name.` };
      if (!isText(text)) return { ok: false, error: `"${section}.${k}" must be text.` };
      if (text.length > MAX_TEXT) return { ok: false, error: `"${section}.${k}" is longer than ${MAX_TEXT} characters.` };
      if (text.trim()) out[section][k.trim()] = text.trim();
    }
  }
  const examples = input.examples ?? [];
  if (!Array.isArray(examples) || examples.length > MAX_ENTRIES) return { ok: false, error: '"examples" must be a list.' };
  for (const [i, ex] of examples.entries()) {
    if (!ex || !isText(ex.question) || !isText(ex.sql)) return { ok: false, error: `examples[${i}] needs a question and sql, both text.` };
    if (ex.question.length > MAX_TEXT || ex.sql.length > 8000) return { ok: false, error: `examples[${i}] is too long.` };
    if (ex.question.trim() && ex.sql.trim()) out.examples.push({ question: ex.question.trim(), sql: ex.sql.trim() });
  }
  const instructions = input.instructions ?? [];
  if (!Array.isArray(instructions) || instructions.length > MAX_ENTRIES || !instructions.every(isText)) return { ok: false, error: '"instructions" must be a list of text.' };
  out.instructions = instructions.map((s) => s.trim()).filter(Boolean);
  if (out.instructions.some((s) => s.length > MAX_TEXT)) return { ok: false, error: `An instruction is longer than ${MAX_TEXT} characters.` };
  return { ok: true, value: out };
}

// Writes the file atomically and keeps the previous version next to it as <file>.bak-<time>.
export function saveKnowledge(filePath, knowledge) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  let backup = null;
  if (fs.existsSync(filePath)) {
    backup = `${filePath}.bak-${new Date().toISOString().replace(/[:.]/g, "-")}`;
    fs.copyFileSync(filePath, backup);
  }
  const tmp = `${filePath}.tmp-${process.pid}`;
  fs.writeFileSync(tmp, JSON.stringify(knowledge, null, 2) + "\n");
  fs.renameSync(tmp, filePath);
  return { backup };
}

// Merge a scan draft under the current file: what a person already wrote always wins.
export function mergeDraft(current, draft) {
  return {
    descriptions: { ...(draft.descriptions || {}), ...(current.descriptions || {}) },
    expressions: { ...(draft.expressions || {}), ...(current.expressions || {}) },
    examples: [...(current.examples || []), ...(draft.examples || []).filter((d) => !(current.examples || []).some((c) => c.question === d.question))],
    instructions: [...new Set([...(current.instructions || []), ...(draft.instructions || [])])],
  };
}

// A Claude-style skill file (SKILL.md): the same ontology, for agents that write their own SQL.
export function renderSkill(knowledge, { name = "database-guide", engine = "SQL" } = {}) {
  const slug = String(name).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60) || "database-guide";
  const lines = [
    "---",
    `name: ${slug}`,
    `description: How to query this ${engine} database correctly: what tables and columns mean, how they join, and the company's definitions of revenue-style terms. Use before writing SQL against it.`,
    "---", "",
    "# Querying this database", "",
    "Generated by db-agent from the team's shared knowledge file. Edit it in db-agent, not here.", "",
  ];
  if (knowledge.instructions.length) {
    lines.push("## Rules", "", ...knowledge.instructions.map((s) => `- ${s}`), "");
  }
  const expr = Object.entries(knowledge.expressions);
  if (expr.length) lines.push("## Business definitions", "", ...expr.map(([k, v]) => `- **${k}**: \`${v}\``), "");
  const byTable = new Map();
  for (const [key, text] of Object.entries(knowledge.descriptions)) {
    const [table, ...rest] = key.split(".");
    if (!byTable.has(table)) byTable.set(table, []);
    byTable.get(table).push([rest.join("."), text]);
  }
  if (byTable.size) {
    lines.push("## Tables and columns", "");
    for (const [table, items] of byTable) {
      const own = items.find(([c]) => c === "");
      lines.push(`### ${table}`, "");
      if (own) lines.push(own[1], "");
      for (const [col, text] of items) if (col) lines.push(`- \`${col}\`: ${text}`);
      if (items.some(([c]) => c)) lines.push("");
    }
  }
  if (knowledge.examples.length) {
    lines.push("## Worked examples", "");
    for (const ex of knowledge.examples) lines.push(`Question: ${ex.question}`, "", "```sql", ex.sql, "```", "");
  }
  return lines.join("\n");
}
